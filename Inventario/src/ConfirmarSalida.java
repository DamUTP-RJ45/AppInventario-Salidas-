    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    
        if (!txtMotivo.getText().equals("")){
            try {   
                PreparedStatement pst = cn.prepareStatement("insert into " + BaseP + ".Salida (Cantidad, Fecha, Hora, Usuario, Producto, Motivo) values (?, ?, ?, ?, ?, ?);");           

                double Cant = Double.parseDouble(txtCanDatSal.getText());
                pst.setDouble(1, Cant);

                pst.setString(2, txtFechaDatSal.getText());

                pst.setString(3, txtHrsDatSal.getText());

                pst.setString(4, txtTurnDatSal.getText());

                pst.setString(5, txtProdDatSal.getText());
            
                pst.setString(6, txtMotivo.getText());

                System.out.println(pst);
                
                pst.executeUpdate();
                
                
            
                }catch (SQLException ex) {
                    Logger.getLogger(NuevaC.class.getName()).log(Level.SEVERE, null, ex);
                }
            NS.ConsDatosSalida();
            this.dispose();
            
            UpCant();
        }else{
            JOptionPane.showMessageDialog(null, "Para poder continuar debes de especificar el motivo de la salida", "Advertencia",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

