    public void UpCant(){
        
        double totalcant = 0;
        int FT = 0;
        
        String sql1 = "SELECT Cantidad FROM " + BaseP + ".Salida WHERE Producto = ?";  
        String sql2 = "update " + BaseP + ".Producto set cantidad = ? where Producto = ?";
             
        
        try(PreparedStatement pst1 = cn.prepareStatement(sql1)){
            pst1.setString(1, txtProdDatSal.getText());
            
            try(ResultSet rs1 = pst1.executeQuery()){
                while(rs1.next()){
                    FT++;
                    totalcant += rs1.getDouble(1);
                }
            }
            
            if(FT > 0){
                try(PreparedStatement pst2 = cn.prepareStatement(sql2)){
                    pst2.setDouble(1, totalcant);
                    pst2.setString(2, txtProdDatSal.getText());
                    
                    pst2.executeUpdate();
                }
            }  
        }catch(SQLException ex){
            Logger.getLogger(Admin.class.getName()).log(Level.SEVERE, "Error al calcular la cantidad total", ex);
            return; 
        }        
    }
